#!/bin/bash

# Имя исходного файла и бинарника
SRC_FILE="sequence.c"
EXEC_FILE="sequence"

echo "=== Компиляция программы ==="
mpicc -o "$EXEC_FILE" "$SRC_FILE" -lm

if [ $? -ne 0 ]; then
    echo "Ошибка компиляции! Проверьте код."
    exit 1
fi

echo -hr
echo "Запуск экспериментов..."
echo "--------------------------------------------------------"
printf "%-10s | %-20s | %-15s\n" "Процессы (p)" "Время (сек)" "Сумма (S)"
echo "--------------------------------------------------------"

# Массив значений числа процессов (p) согласно методичке УГАТУ
# Вы можете добавить или убрать значения, например: 1 2 4 8 16 32 64 128
PROCESS_COUNTS=(1 2 4 8 16 32)

for p in "${PROCESS_COUNTS[@]}"; do
    # Запускаем mpirun и сохраняем вывод
    output=$(mpirun -np "$p" ./"$EXEC_FILE")

    # Извлекаем время и сумму из вывода программы с помощью awk/grep
    time_val=$(echo "$output" | grep "time elapsed" | awk '{print $4}')
    sum_val=$(echo "$output" | grep "S =" | awk '{print $3}')

    # Выводим строчку в таблицу
    printf "%-10d | %-20s | %-15s\n" "$p" "$time_val" "$sum_val"
done

echo "--------------------------------------------------------"
echo "Эксперименты завершены!"
